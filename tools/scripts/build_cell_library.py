"""The game's CellML modules in libcuflynx's generated C (docs/plans/libcuflynx-solver.md): the aod_modules library.

Regenerates src/AdaptOrDeity.Cells/generated from the modules of content/modules.lock.json through libcuflynx (one
module array holding an instance of each module, unconnected, so each is its own set of blocks; BE_batched_c's C with
the lock's outputs), plus aod_modules_meta.c (each module's type, version, licence, source digest and named parameter
sets), then builds it with CMake into src/AdaptOrDeity.Native/bin/cells: libaod_modules.so (.dll, .dylib) and the
static libaod_modules_static.a (aod_modules_static.lib) for the NativeAOT library.

    <libcuflynx venv>/bin/python tools/scripts/build_cell_library.py            # regenerate and build
    <libcuflynx venv>/bin/python tools/scripts/build_cell_library.py --build    # build the committed sources only

--build needs only CMake and a C compiler (no libcuflynx, no libCellML): what CI does on every platform.
"""
import csv
import json
import os
import shutil
import subprocess
import sys
import tempfile
import time

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CELLS = os.path.join(REPO, 'src', 'AdaptOrDeity.Cells')
GENERATED = os.path.join(CELLS, 'generated')
MODULES_ROOT = os.path.join(REPO, 'external', 'circulatory-autogen-modules', 'modules')
SOURCES = ('model0d_core.c', 'model0d_core.h', 'batched_kernels.c', 'batched_kernels.h', 'batched_runtime.c')

#: The instance name each locked module gets in the module array (its parameters are <name>_<instance>, its states
#: and variables in component <instance>_module).
INSTANCE_NAMES = {('generic_adaptive_cell', 'fermenter'): 'cell_0', ('tissue_diffusion_volume', 'nn'): 'vol_0'}


def _locked_modules():
    with open(os.path.join(REPO, 'content', 'modules.lock.json')) as f:
        lock = json.load(f)
    entries = lock['modules'] if isinstance(lock, dict) and 'modules' in lock else lock
    return [e for e in entries if isinstance(e, dict) and 'module_type' in e]


def _version_dir(entry):
    root = os.path.join(REPO, entry['root']) if entry.get('root') else os.path.join(MODULES_ROOT, entry['category'])
    return os.path.join(root, entry['module_type'], 'versions', entry['version'])


def _instance_values(entry, instance):
    path = os.path.join(_version_dir(entry), 'instances', instance, f'{instance}_parameters.csv')
    with open(path, newline='') as f:
        return [(row['variable_name'], float(row['value'])) for row in csv.DictReader(f)]


def _c_string(text):
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"') + '"'


def metadata_c(modules):
    """aod_modules_meta.c: the modules' descriptions and named parameter sets, for the game to find them by name."""
    lines = ['/* The game\'s modules in this library: type, version, licence, source digest and named parameter sets.',
             '   Generated by tools/scripts/build_cell_library.py from content/modules.lock.json; regenerate instead of',
             '   editing. */',
             '#if defined(_WIN32)', '#define AOD_API __declspec(dllexport)', '#else',
             '#define AOD_API __attribute__((visibility("default")))', '#endif', '',
             'typedef struct { const char *name; double value; } AodParam;',
             'typedef struct { const char *name; int n; const AodParam *params; } AodInstance;',
             'typedef struct { const char *name, *type, *version, *licence, *sha256; int n; const AodInstance *instances; '
             '} AodModule;', '']
    rows = []
    for m, (entry, name, licence) in enumerate(modules):
        instance_rows = []
        for i, instance in enumerate(entry.get('instances', ['default'])):
            params = _instance_values(entry, instance)
            lines.append(f'static const AodParam P{m}_{i}[] = {{')
            lines += [f'    {{ {_c_string(p)}, {v!r} }},' for p, v in params] + ['    { 0, 0.0 }', '};']
            instance_rows.append(f'{{ {_c_string(instance)}, {len(params)}, P{m}_{i} }}')
        lines.append(f'static const AodInstance I{m}[] = {{ {", ".join(instance_rows)} }};')
        rows.append(f'    {{ {_c_string(name)}, {_c_string(entry["module_type"])}, {_c_string(entry["version"])}, '
                    f'{_c_string(licence)}, {_c_string(entry.get("sha256", ""))}, {len(instance_rows)}, I{m} }},')
    lines += ['', 'static const AodModule AOD_MODULES[] = {'] + rows + ['};', '',
              f'AOD_API int aod_module_count(void) {{ return {len(modules)}; }}',
              'AOD_API const char *aod_module_name(int m) { return AOD_MODULES[m].name; }',
              'AOD_API const char *aod_module_type(int m) { return AOD_MODULES[m].type; }',
              'AOD_API const char *aod_module_version(int m) { return AOD_MODULES[m].version; }',
              'AOD_API const char *aod_module_licence(int m) { return AOD_MODULES[m].licence; }',
              'AOD_API const char *aod_module_sha256(int m) { return AOD_MODULES[m].sha256; }',
              'AOD_API int aod_instance_count(int m) { return AOD_MODULES[m].n; }',
              'AOD_API const char *aod_instance_name(int m, int i) { return AOD_MODULES[m].instances[i].name; }',
              'AOD_API int aod_instance_param_count(int m, int i) { return AOD_MODULES[m].instances[i].n; }',
              'AOD_API const char *aod_instance_param_name(int m, int i, int k) '
              '{ return AOD_MODULES[m].instances[i].params[k].name; }',
              'AOD_API double aod_instance_param_value(int m, int i, int k) '
              '{ return AOD_MODULES[m].instances[i].params[k].value; }', '']
    return '\n'.join(lines)


def regenerate():
    from libcuflynx.scripts.script_generate_with_new_architecture import generate_with_new_architecture
    from libcuflynx.generators import kernel_ir
    from libcuflynx.generators.cpp import batched

    modules, records, outputs = [], [], []
    for entry in _locked_modules():
        name = INSTANCE_NAMES[(entry['module_type'], entry['version'])]
        stem = f'{entry["module_type"]}_{entry["version"]}'
        with open(os.path.join(_version_dir(entry), f'{stem}_modules_config.json')) as f:
            config = next(c for c in json.load(f) if c.get('module_subtype') == entry['version'])
        modules.append((entry, name, config.get('licence', '')))
        records.append({'name': name, 'module_type': entry['module_type'], 'module_subtype': entry['version'],
                        'instance': 'default', 'inp_instances': [], 'out_instances': []})
        # the values the game reads after every step (the lock's "outputs"); the rest are computed on demand
        outputs += [f'{name}_module/{o}' for o in entry.get('outputs', [])]

    work = tempfile.mkdtemp(prefix='aod_modules_')
    res = os.path.join(work, 'res')
    os.makedirs(res)
    with open(os.path.join(res, 'modules_module_array.json'), 'w') as f:
        json.dump(records, f)
    with open(os.path.join(res, 'modules_parameters.csv'), 'w') as f:
        f.write('variable_name,units,value,data_reference\n')
    assert generate_with_new_architecture(False, {
        'file_prefix': 'modules', 'input_param_file': 'modules_parameters.csv', 'model_type': 'cellml',
        'solver': 'CVODE_myokit', 'resources_dir': res, 'generated_models_dir': os.path.join(work, 'gen'),
        'module_library_dirs': [os.path.join(REPO, 'content', 'assembled')] + sorted(
            {os.path.dirname(os.path.dirname(os.path.dirname(_version_dir(e)))) for e, _, _ in modules
             if not e.get('root')}),
        'use_builtin_modules': False, 'DEBUG': False})
    flat, am = kernel_ir.analyse_cellml(os.path.join(work, 'gen', 'modules', 'modules.cellml'))
    km = kernel_ir.build_kernel_model(am)
    files = batched.sources(am, km, 'aod_modules', outputs, batched.describe(flat, am, km)['state_init_ref'])
    files['aod_modules_meta.c'] = metadata_c(modules)
    shutil.rmtree(GENERATED, ignore_errors=True)
    os.makedirs(GENERATED)
    for name in SOURCES + ('aod_modules_meta.c',):
        with open(os.path.join(GENERATED, name), 'w', newline='\n') as f:
            f.write(files[name])
    shutil.rmtree(work, ignore_errors=True)


def build():
    build_dir = os.path.join(REPO, 'build', 'cells')
    subprocess.run(['cmake', '-S', CELLS, '-B', build_dir, '-DCMAKE_BUILD_TYPE=Release'], check=True,
                   stdout=subprocess.DEVNULL)
    subprocess.run(['cmake', '--build', build_dir, '--config', 'Release'], check=True, stdout=subprocess.DEVNULL)


if __name__ == '__main__':
    t0 = time.perf_counter()
    if '--build' not in sys.argv[1:]:
        regenerate()
    t1 = time.perf_counter()
    build()
    out = os.path.join(REPO, 'src', 'AdaptOrDeity.Native', 'bin', 'cells')
    print(f'generated in {t1 - t0:.1f} s, built in {time.perf_counter() - t1:.1f} s:',
          ', '.join(sorted(n for n in os.listdir(out) if 'aod_modules' in n)))
