"""The game's cell as libcuflynx's BE_batched_c library (docs/plans/libcuflynx-solver.md): a one-cell module array of
content/assembled, generated by libcuflynx, built as C, and copied to <out>/libaod_cell.so (.dll, .dylib).

Run with a libcuflynx venv that has the batched solver (feat/batched-implicit-solver):
    <venv>/bin/python tools/scripts/build_cell_library.py [out]      # default src/AdaptOrDeity.Native/bin/cells
"""
import ctypes
import json
import os
import shutil
import sys
import time

from libcuflynx.scripts.script_generate_with_new_architecture import generate_with_new_architecture
from libcuflynx.generators.cpp import batched

repo = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
out = os.path.abspath(sys.argv[1]) if len(sys.argv) > 1 else os.path.join(repo, 'src', 'AdaptOrDeity.Native', 'bin', 'cells')
work = os.path.join(out, 'work')
res = os.path.join(work, 'res'); os.makedirs(res, exist_ok=True)
records = [{'name': 'cell_0', 'module_type': 'generic_adaptive_cell', 'module_subtype': 'fermenter',
            'instance': 'default', 'inp_instances': [], 'out_instances': []}]
open(os.path.join(res, 'cell_module_array.json'), 'w').write(json.dumps(records))
open(os.path.join(res, 'cell_parameters.csv'), 'w').write('variable_name,units,value,data_reference\n')
t0 = time.perf_counter()
assert generate_with_new_architecture(False, {
    'file_prefix': 'cell', 'input_param_file': 'cell_parameters.csv', 'model_type': 'cellml', 'solver': 'CVODE_myokit',
    'resources_dir': res, 'generated_models_dir': os.path.join(work, 'gen'),
    'module_library_dirs': [os.path.join(repo, 'content', 'assembled')], 'use_builtin_modules': False, 'DEBUG': False})
t1 = time.perf_counter()
cellml = os.path.join(work, 'gen', 'cell', 'cell.cellml')
desc, path, build_s, cached = batched.load_or_build(cellml, os.path.join(work, 'build'))
print(f'generated in {t1 - t0:.1f} s; library built in {time.perf_counter() - t1:.1f} s')
target = os.path.join(out, 'libaod_cell' + os.path.splitext(path)[1])
shutil.copyfile(path, target)
lib = ctypes.CDLL(target)
s = ctypes.c_char_p
lib.bk_variable_info.restype = ctypes.c_int
names = []
for i in range(lib.bk_variable_count()):
    n, u, c = s(), s(), s()
    kind = lib.bk_variable_info(i, ctypes.byref(n), ctypes.byref(u), ctypes.byref(c))
    names.append((c.value.decode(), n.value.decode(), u.value.decode(), kind))
print(lib.bk_state_count(), 'states,', len(names), 'variables; kernels', lib.bk_kernel_count(),
      '; kinds', {k: sum(1 for x in names if x[3] == k) for k in range(6)})
print(target)
